std::vector<float> readF32(const QString& path) {
    QFile file(path);
    if (!file.open(QIODevice::ReadOnly)) {
        return {};
    }
    const QByteArray bytes = file.readAll();
    std::vector<float> data(bytes.size() / sizeof(float));
    std::memcpy(data.data(), bytes.constData(), data.size() * sizeof(float));
    return data;
}

std::vector<double> readTimes(const QString& path) {
    std::vector<double> times;
    QFile file(path);
    if (file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        while (!file.atEnd()) {
            bool ok = false;
            const double t = file.readLine().trimmed().toDouble(&ok);
            if (ok) {
                times.push_back(t);
            }
        }
    }
    return times;
}

/// Minimal reader for the 16-bit PCM stereo WAV test excerpt.
/// Samples are scaled by 1 / 32768, like soundfile in the reference.
std::vector<float> readWavStereo16(const QString& path, double* pSampleRate) {
    QFile file(path);
    if (!file.open(QIODevice::ReadOnly)) {
        return {};
    }
    const QByteArray bytes = file.readAll();
    const auto u16 = [&bytes](int pos) {
        return static_cast<quint16>(static_cast<quint8>(bytes[pos]) |
                (static_cast<quint8>(bytes[pos + 1]) << 8));
    };
    const auto u32 = [&](int pos) {
        return static_cast<quint32>(u16(pos)) | (static_cast<quint32>(u16(pos + 2)) << 16);
    };
    if (bytes.size() < 12 || !bytes.startsWith("RIFF") || bytes.mid(8, 4) != "WAVE") {
        return {};
    }
    int pos = 12;
    int channels = 0;
    int bits = 0;
    while (pos + 8 <= bytes.size()) {
        const QByteArray id = bytes.mid(pos, 4);
        const int size = static_cast<int>(u32(pos + 4));
        const int body = pos + 8;
        if (id == "fmt ") {
            channels = u16(body + 2);
            *pSampleRate = u32(body + 4);
            bits = u16(body + 14);
        } else if (id == "data") {
            if (channels != 2 || bits != 16) {
                return {};
            }
            const int count = std::min(size, static_cast<int>(bytes.size()) - body) / 2;
            std::vector<float> samples(count);
            for (int i = 0; i < count; ++i) {
                samples[i] = static_cast<qint16>(u16(body + 2 * i)) / 32768.0f;
            }
            return samples;
        }
        pos = body + size + (size & 1);
    }
    return {};
}

float maxAbsDiff(const std::vector<float>& a, const std::vector<float>& b) {
    float result = 0.0f;
    for (size_t i = 0; i < std::min(a.size(), b.size()); ++i) {
        result = std::max(result, std::abs(a[i] - b[i]));
    }
    return result;
}

/// Feeds interleaved stereo samples to a beats plugin, in blocks of
/// kAnalysisFramesPerChunk frames like AnalyzerThread does.
bool analyze(AnalyzerBeatsPlugin* pPlugin,
        const std::vector<float>& stereo,
        audio::SampleRate sampleRate) {
    if (!pPlugin->initialize(sampleRate)) {
        return false;
    }
    constexpr size_t kBlock = kAnalysisFramesPerChunk * 2;
    for (size_t i = 0; i < stereo.size(); i += kBlock) {
        const SINT len = static_cast<SINT>(std::min(kBlock, stereo.size() - i));
        if (!pPlugin->processSamples(&stereo[i], len)) {
            return false;
        }
    }
    return pPlugin->finalize();
}

