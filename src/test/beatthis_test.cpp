class BeatThisTest : public MixxxTest {
  protected:
    QString dataFile(const QString& name) const {
        return getTestDir().filePath(QStringLiteral("beatthis/") + name);
    }
    QString modelPath() const {
        return AnalyzerBeatThis::defaultModelPath(config());
    }
    std::vector<float> computeSpect(size_t blockSize) const {
        const auto mono = readF32(dataFile("mono22050.f32"));
        MelSpectrogram mel;
        std::vector<float> spect;
        const auto collect = [&spect](const float* pFrame) {
            spect.insert(spect.end(), pFrame, pFrame + kNumMels);
            return true;
        };
        for (size_t i = 0; i < mono.size(); i += blockSize) {
            EXPECT_TRUE(mel.process(&mono[i], std::min(blockSize, mono.size() - i), collect));
        }
        EXPECT_TRUE(mel.finish(collect));
        return spect;
    }
};

TEST_F(BeatThisTest, FilterbankMatchesTorchaudio) {
    const auto reference = readF32(dataFile("filterbank.f32"));
    ASSERT_FALSE(reference.empty());
    const auto fb = MelSpectrogram::makeSlaneyFilterbank();
    ASSERT_EQ(fb.size(), reference.size());
    // torchaudio computes the filterbank in float32 (observed error: 1.3e-5)
    EXPECT_LT(maxAbsDiff(fb, reference), 5e-5f);
}

TEST_F(BeatThisTest, ResamplerMatchesReference) {
    double sampleRate = 0;
    const auto stereo = readWavStereo16(dataFile("excerpt.wav"), &sampleRate);
    const auto reference = readF32(dataFile("mono22050.f32"));
    ASSERT_FALSE(stereo.empty());
    ASSERT_FALSE(reference.empty());

    Resampler resampler(sampleRate);
    ASSERT_TRUE(resampler.isValid());
    std::vector<float> mono;
    constexpr size_t kBlock = kAnalysisFramesPerChunk * 2;
    for (size_t i = 0; i < stereo.size(); i += kBlock) {
        const size_t len = std::min(kBlock, stereo.size() - i);
        ASSERT_TRUE(resampler.processStereo(&stereo[i], static_cast<SINT>(len / 2), &mono));
    }
    ASSERT_TRUE(resampler.flush(&mono));

    // Same length and no time shift: soxr compensates its group delay.
    ASSERT_EQ(mono.size(), reference.size());
    EXPECT_LT(maxAbsDiff(mono, reference), 1e-4f);
}

TEST_F(BeatThisTest, ResamplerPassthroughAtModelRate) {
    const std::vector<float> stereo = {0.1f, 0.3f, -0.5f, 0.5f, 1.0f, 0.0f};
    Resampler resampler(kModelSampleRate);
    ASSERT_TRUE(resampler.isValid());
    std::vector<float> mono;
    ASSERT_TRUE(resampler.processStereo(stereo.data(), 3, &mono));
    ASSERT_TRUE(resampler.flush(&mono));
    ASSERT_EQ(mono.size(), 3u);
    EXPECT_FLOAT_EQ(mono[0], 0.2f);
    EXPECT_FLOAT_EQ(mono[1], 0.0f);
    EXPECT_FLOAT_EQ(mono[2], 0.5f);
}

TEST_F(BeatThisTest, MelSpectrogramMatchesReference) {
    const auto reference = readF32(dataFile("spect.f32"));
    ASSERT_FALSE(reference.empty());
    const auto spect = computeSpect(4096);
    ASSERT_EQ(spect.size(), reference.size()); // same number of frames
    EXPECT_LT(maxAbsDiff(spect, reference), 1e-3f);
}

TEST_F(BeatThisTest, MelSpectrogramIsBlockSizeInvariant) {
    const auto a = computeSpect(1);
    const auto b = computeSpect(441);
    const auto c = computeSpect(100000);
    ASSERT_FALSE(a.empty());
    ASSERT_EQ(a.size(), b.size());
    ASSERT_EQ(a.size(), c.size());
    EXPECT_EQ(maxAbsDiff(a, b), 0.0f);
    EXPECT_EQ(maxAbsDiff(a, c), 0.0f);
}

TEST_F(BeatThisTest, MelSpectrogramRejectsTooShortSignal) {
    const std::vector<float> samples(kMinSamples - 1, 0.1f);
    MelSpectrogram mel;
    int frames = 0;
    const auto count = [&frames](const float*) {
        ++frames;
        return true;
    };
    EXPECT_TRUE(mel.process(samples.data(), samples.size(), count));
    EXPECT_FALSE(mel.finish(count));
    EXPECT_EQ(frames, 0);
}

TEST_F(BeatThisTest, PeakPickingMatchesReferenceRules) {
    std::vector<float> logits(100, -5.0f);
    logits[10] = 2.0f; // isolated peak
    logits[20] = 1.0f; // equal adjacent peaks, merged at 20.5
    logits[21] = 1.0f;
    logits[40] = 3.0f; // 43 is masked by 40 (window of 7)
    logits[43] = 1.0f;
    logits[60] = -0.5f; // local maximum, but logit < 0
    const auto times = Chunker::pickPeaks(logits);
    ASSERT_EQ(times.size(), 3u);
    EXPECT_DOUBLE_EQ(times[0], 10.0 / kFramesPerSecond);
    EXPECT_DOUBLE_EQ(times[1], 20.5 / kFramesPerSecond);
    EXPECT_DOUBLE_EQ(times[2], 40.0 / kFramesPerSecond);
}

TEST_F(BeatThisTest, ChunkerMatchesReference) {
    auto pModel = Model::load(modelPath());
    if (!pModel) {
        GTEST_SKIP() << "Beat This! model not available";
    }
    const auto spect = readF32(dataFile("spect.f32"));
    const auto refBeat = readF32(dataFile("beat_logits.f32"));
    const auto refDownbeat = readF32(dataFile("downbeat_logits.f32"));
    ASSERT_FALSE(spect.empty());
    Chunker chunker(pModel);
    for (size_t i = 0; i < spect.size(); i += kNumMels) {
        ASSERT_TRUE(chunker.addFrame(&spect[i]));
    }
    ASSERT_TRUE(chunker.finish());
    ASSERT_EQ(chunker.beatLogits().size(), refBeat.size());
    ASSERT_EQ(chunker.downbeatLogits().size(), refDownbeat.size());
    EXPECT_LT(maxAbsDiff(chunker.beatLogits(), refBeat), 1e-2f);
    EXPECT_LT(maxAbsDiff(chunker.downbeatLogits(), refDownbeat), 1e-2f);

    const auto refBeats = readTimes(dataFile("beats.txt"));
    const auto refDownbeats = readTimes(dataFile("downbeats.txt"));
    const auto beats = chunker.beatTimes();
    const auto downbeats = chunker.downbeatTimes();
    ASSERT_EQ(beats.size(), refBeats.size());
    for (size_t i = 0; i < beats.size(); ++i) {
        EXPECT_NEAR(beats[i], refBeats[i], 1e-6);
    }
    ASSERT_EQ(downbeats.size(), refDownbeats.size());
    for (size_t i = 0; i < downbeats.size(); ++i) {
        EXPECT_NEAR(downbeats[i], refDownbeats[i], 1e-6);
    }
}

TEST_F(BeatThisTest, EndToEndBeatsMatchReference) {
    if (!Model::load(modelPath())) {
        GTEST_SKIP() << "Beat This! model not available";
    }
    double sampleRate = 0;
    const auto stereo = readWavStereo16(dataFile("excerpt.wav"), &sampleRate);
    const auto refBeats = readTimes(dataFile("beats.txt"));
    ASSERT_FALSE(stereo.empty());
    ASSERT_EQ(sampleRate, readTimes(dataFile("samplerate.txt")).at(0));

    AnalyzerBeatThis analyzer(modelPath());
    ASSERT_TRUE(analyze(&analyzer,
            stereo,
            audio::SampleRate(static_cast<audio::SampleRate::value_t>(sampleRate))));

    const auto beats = analyzer.getBeats();
    ASSERT_EQ(static_cast<size_t>(beats.size()), refBeats.size());
    for (int i = 0; i < beats.size(); ++i) {
        EXPECT_NEAR(beats[i].value() / sampleRate, refBeats[i], 0.005); // 5 ms
    }
    EXPECT_FALSE(analyzer.getDownbeats().isEmpty());
}

TEST_F(BeatThisTest, ShortTrack) {
    if (!Model::load(modelPath())) {
        GTEST_SKIP() << "Beat This! model not available";
    }
    double sampleRate = 0;
    auto stereo = readWavStereo16(dataFile("excerpt.wav"), &sampleRate);
    ASSERT_FALSE(stereo.empty());
    const auto rate = audio::SampleRate(static_cast<audio::SampleRate::value_t>(sampleRate));

    // 10 s: a single chunk, shorter than the model input.
    std::vector<float> excerpt(stereo.begin() + static_cast<size_t>(8 * sampleRate) * 2,
            stereo.begin() + static_cast<size_t>(18 * sampleRate) * 2);
    AnalyzerBeatThis analyzer(modelPath());
    ASSERT_TRUE(analyze(&analyzer, excerpt, rate));
    EXPECT_GT(analyzer.getBeats().size(), 10);

    // A few samples only: the analysis fails cleanly.
    excerpt.resize(200);
    EXPECT_FALSE(analyze(&analyzer, excerpt, rate));
    EXPECT_TRUE(analyzer.getBeats().isEmpty());
}

