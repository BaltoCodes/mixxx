/// Quality benchmark, disabled by default. Run with
///   MIXXX_BEATTHIS_BENCHMARK_DIR=/path/to/audio
///   MIXXX_BEATTHIS_BENCHMARK_OUT=/path/to/output
///   mixxx-test --gtest_also_run_disabled_tests
///       --gtest_filter=BeatThisBenchmark.DISABLED_Benchmark
/// and evaluate the output with tools/beatthis/benchmark.py.
class BeatThisBenchmark : public MixxxTest, ::SoundSourceProviderRegistration {
  protected:
    struct Result {
        QVector<audio::FramePos> beats;
        double gridBpm = 0;
        double gridFirstBeat = 0;
    };

    static std::vector<float> decode(const QString& filePath, audio::SampleRate* pSampleRate) {
        auto pTrack = Track::newTemporary(filePath);
        SoundSourceProxy proxy(pTrack);
        AudioSource::OpenParams openParams;
        openParams.setChannelCount(audio::ChannelCount::stereo());
        auto pAudioSource = proxy.openAudioSource(openParams);
        if (!pAudioSource) {
            return {};
        }
        if (pAudioSource->getSignalInfo().getChannelCount() != audio::ChannelCount::stereo()) {
            pAudioSource = AudioSourceStereoProxy::create(pAudioSource, kAnalysisFramesPerChunk);
        }
        *pSampleRate = pAudioSource->getSignalInfo().getSampleRate();
        std::vector<float> stereo;
        SampleBuffer buffer(kAnalysisFramesPerChunk * 2);
        auto index = pAudioSource->frameIndexRange().start();
        while (index < pAudioSource->frameIndexRange().end()) {
            const auto range = IndexRange::forward(index,
                    std::min<SINT>(kAnalysisFramesPerChunk,
                            pAudioSource->frameIndexRange().end() - index));
            const auto read = pAudioSource->readSampleFrames(WritableSampleFrames(
                    range, SampleBuffer::WritableSlice(buffer.data(), buffer.size())));
            if (read.frameIndexRange().empty()) {
                break;
            }
            stereo.insert(stereo.end(),
                    read.readableData(),
                    read.readableData() + read.readableLength());
            index = read.frameIndexRange().end();
        }
        return stereo;
    }

    static Result run(AnalyzerBeatsPlugin* pPlugin,
            const std::vector<float>& stereo,
            audio::SampleRate sampleRate) {
        Result result;
        if (!analyze(pPlugin, stereo, sampleRate)) {
            return result;
        }
        result.beats = pPlugin->getBeats();
        QHash<QString, QString> versionInfo;
        versionInfo["vamp_plugin_id"] = pPlugin->id();
        const auto pBeats = BeatFactory::makePreferredBeats(
                result.beats, versionInfo, true, sampleRate);
        if (pBeats) {
            const auto end = audio::FramePos(static_cast<double>(stereo.size() / 2));
            result.gridBpm = pBeats->getBpmInRange(audio::kStartFramePos, end).value();
            result.gridFirstBeat = pBeats->firstBeat().value() / sampleRate.toDouble();
        }
        return result;
    }
};

TEST_F(BeatThisBenchmark, DISABLED_Benchmark) {
    const QString inDir = qEnvironmentVariable("MIXXX_BEATTHIS_BENCHMARK_DIR");
    const QString outDir = qEnvironmentVariable("MIXXX_BEATTHIS_BENCHMARK_OUT");
    if (inDir.isEmpty() || outDir.isEmpty()) {
        GTEST_SKIP() << "Set MIXXX_BEATTHIS_BENCHMARK_DIR and MIXXX_BEATTHIS_BENCHMARK_OUT";
    }
    const QString modelPath = AnalyzerBeatThis::defaultModelPath(config());
    ASSERT_TRUE(Model::load(modelPath)) << "Beat This! model not available";
    ASSERT_TRUE(QDir().mkpath(outDir));

    struct Output {
        QString name;
        std::function<std::unique_ptr<AnalyzerBeatsPlugin>()> create;
        std::unique_ptr<QFile> pBeatsFile;
        std::unique_ptr<QFile> pGridFile;
    };
    std::vector<Output> outputs;
    outputs.push_back({QStringLiteral("queenmary"),
            [] { return std::make_unique<AnalyzerQueenMaryBeats>(); },
            nullptr,
            nullptr});
    outputs.push_back({QStringLiteral("beatthis"), [modelPath] {
                           return std::make_unique<AnalyzerBeatThis>(modelPath);
                       },
            nullptr,
            nullptr});
    for (auto& output : outputs) {
        output.pBeatsFile = std::make_unique<QFile>(
                QDir(outDir).filePath(output.name + QStringLiteral(".beats.tsv")));
        output.pGridFile = std::make_unique<QFile>(
                QDir(outDir).filePath(output.name + QStringLiteral(".grid.tsv")));
        ASSERT_TRUE(output.pBeatsFile->open(QIODevice::WriteOnly | QIODevice::Text));
        ASSERT_TRUE(output.pGridFile->open(QIODevice::WriteOnly | QIODevice::Text));
    }

    QDirIterator it(inDir, QDir::Files, QDirIterator::Subdirectories);
    while (it.hasNext()) {
        const QString filePath = it.next();
        if (!SoundSourceProxy::isFileNameSupported(filePath)) {
            continue;
        }
        audio::SampleRate sampleRate;
        const auto stereo = decode(filePath, &sampleRate);
        if (stereo.empty()) {
            qWarning() << "Skipping undecodable file" << filePath;
            continue;
        }
        const QString relPath = QDir(inDir).relativeFilePath(filePath);
        for (auto& output : outputs) {
            auto pPlugin = output.create();
            const Result result = run(pPlugin.get(), stereo, sampleRate);
            // One line per file: relative path, then the beat times in seconds.
            QTextStream beats(output.pBeatsFile.get());
            beats << relPath;
            for (const auto& beat : result.beats) {
                beats << '\t' << QString::number(beat.value() / sampleRate.toDouble(), 'f', 6);
            }
            beats << '\n';
            QTextStream grid(output.pGridFile.get());
            grid << relPath << '\t' << QString::number(result.gridBpm, 'f', 4) << '\t'
                 << QString::number(result.gridFirstBeat, 'f', 6) << '\t'
                 << QString::number(stereo.size() / 2 / sampleRate.toDouble(), 'f', 3)
                 << '\n';
        }
        qInfo() << "Analyzed" << relPath;
    }
}
